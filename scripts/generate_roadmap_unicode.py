#!/usr/bin/env python3
"""Generate the report's Unicode 15.1.0 layout ranges using Python 3.13.

Only this build-time script imports unicodedata. Unassigned characters are not
wide: Python's UCD returns F for many unassigned code points. Runtime layout uses
these committed ranges, including marks assigned after Python 3.10's Unicode 13.
"""
from __future__ import annotations

import argparse
import sys
import unicodedata
from pathlib import Path

DESTINATION = Path(__file__).resolve().parents[1] / 'src/bat_agent_connector/pm_roadmap_unicode.py'
VERSION = '15.1.0'


def ranges(predicate):
    result = []
    for value in range(0x110000):
        if predicate(chr(value)):
            if result and result[-1][1] == value - 1:
                result[-1] = result[-1][0], value
            else:
                result.append((value, value))
    return result


def generate():
    if sys.version_info[:2] != (3, 13) or unicodedata.unidata_version != VERSION:
        raise RuntimeError('Generate only with Python 3.13 and Unicode ' + VERSION)
    properties = {
        'WIDE': ranges(lambda c: unicodedata.category(c) != 'Cn' and unicodedata.east_asian_width(c) in {'W', 'F'}),
        'MARK': ranges(lambda c: unicodedata.category(c) in {'Mn', 'Mc', 'Me'}),
        'VARIATION': [(0xFE00, 0xFE0F), (0xE0100, 0xE01EF)],
        'ZWJ': [(0x200D, 0x200D)], 'REGIONAL': [(0x1F1E6, 0x1F1FF)],
        'MODIFIER': [(0x1F3FB, 0x1F3FF)],
        'CONTROL': [(0, 9), (11, 31), (0x7F, 0x9F)],
        'BIDI': [(0x061C, 0x061C), (0x200E, 0x200F), (0x202A, 0x202E), (0x2066, 0x2069)],
        'NONCHARACTER': [(0xFDD0, 0xFDEF), *[(plane * 0x10000 + 0xFFFE, plane * 0x10000 + 0xFFFF) for plane in range(17)]],
        'SURROGATE': [(0xD800, 0xDFFF)],
    }
    lines = ['"""Generated by scripts/generate_roadmap_unicode.py; do not edit by hand."""',
             '', f"UNICODE_VERSION = '{VERSION}'"]
    for name, values in properties.items():
        lines += ['', name + ' = (']
        lines += [f'    (0x{first:X}, 0x{last:X}),' for first, last in values]
        lines += [')']
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=DESTINATION)
    args = parser.parse_args()
    output = generate()
    if args.check:
        if args.output.read_text() != output:
            raise SystemExit('Committed roadmap Unicode table differs from generator')
    else:
        args.output.write_text(output, encoding='utf-8', newline='\n')
    print(f'Unicode {VERSION}: {len(output.encode())} bytes; {"checked" if args.check else "generated"}')


if __name__ == '__main__':
    main()
