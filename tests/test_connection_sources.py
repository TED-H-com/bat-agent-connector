VECTORS = json.loads(GOLDEN.read_text())


def prepare_directory(root, row):
    for relative, kind in row["entries"].items():
        path = root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        if kind == "directory":
            path.mkdir(exist_ok=True)
        else:
            path.write_text("synthetic non-directory")


def directory_result(root, row):
    configured = row.get("profiles_dir")
    if configured and not configured.startswith("~"):
        configured = root / configured
    environment = {} if row.get("no_appdata") else {"APPDATA": str(root / "roaming")}
    try:
        selected = select_profiles_directory(configured, platform=row["platform"],
            environment=environment, home=root / "home")
        return {"path": selected.relative_to(root).as_posix()}
    except SourceUnavailable as error:
        return {"reason": str(error)}


def token_result(row, mode):
    result = parse_token_store(row["store"], mode=mode).lookup(row["profile_id"])
    return {"state": result.state, "reason": result.reason}


def test_policy_vectors_match_producer(tmp_path):
    """Generate shared admission/listing entries; preserve reviewed runtime columns."""
    actual = json.loads(GOLDEN.read_text())
    assert actual["policy"] == BAT_SOURCE_POLICY == 1
    actual["provenance"]["inputs"] = "Every directory/store/index input is hand-written synthetic data; none is a captured BAT store. Index inputs are produced by tests.source_policy_inputs.profile_index_inputs."
    actual["provenance"]["python_expected"] = "Shared admission and profile_indexes expectations are generated by the real connection_sources readers, with listing output checked through managed_setup._profiles. Regenerate with BATC_UPDATE_SOURCE_POLICY=1 pytest-disktmp uv run pytest -q tests/test_connection_sources.py. python_runtime remains legacy Python; rust_legacy_fleet remains legacy Fleet, never admission."
    actual["provenance"]["listing"] = "Per-entry skip with fixed positional reasons; ignore additive fields; exclude all case-competing IDs. Kit drift validation remains strict."
    for row in actual["directories"]:
        root = tmp_path / row["id"]
        prepare_directory(root, row)
        denied = root / row["unreadable"] if row.get("unreadable") else None
        if denied:
            denied.chmod(0)
        try:
            outcome = directory_result(root, row)
        finally:
            if denied:
                denied.chmod(0o700)
        row["expected"].pop("python_admission", None)
        row["expected"]["admission"] = outcome
        row["expected"]["python_runtime"] = outcome
    existing = {row["id"] for row in actual["token_stores"]}
    for row in format_error_store_inputs():
        if row["id"] not in existing:
            actual["token_stores"].append({**row, "expected": {
                "rust_legacy_fleet": {"state": "unavailable", "reason": "CREDENTIAL_MISSING"}}})
    for row in actual["token_stores"]:
        row["expected"].pop("python_admission", None)
        row["expected"]["admission"] = token_result(row, TokenMode.ADMISSION)
        row["expected"]["python_runtime"] = token_result(row, TokenMode.LEGACY_RUNTIME)
    actual["profile_indexes"] = [
        {**row, "expected": asdict(parse_profile_index(row["index"]))}
        for row in profile_index_inputs()
    ]
    actual["token_files"] = []
    for row in token_file_inputs():
        directory = tmp_path / row["id"]
        directory.mkdir()
        path = directory / "remote-tokens.enc.json"
        path.write_bytes(bytes(row["store_bytes"]))
        path.chmod(row["mode"])
        result = read_token_store(directory, mode=TokenMode.ADMISSION).lookup("remote-1")
        actual["token_files"].append({**row, "expected": {"state": result.state, "reason": result.reason}})
    actual["profile_files"] = []
    for row in profile_file_inputs():
        directory = prepare_profile_files(tmp_path / row["id"], row)
        result = read_profile_index(directory)
        actual["profile_files"].append({**row, "expected": asdict(result)})
    actual["provenance"]["file_admission"] = "token_files use raw byte arrays and explicit POSIX modes through read_token_store; profile_files use prepare_profile_files and read_profile_index plus setup._profiles. Native consumes the same expected entry through its real catalog and policy resolver. POSIX-only fixtures are skipped on Windows."
    if os.environ.get("BATC_UPDATE_SOURCE_POLICY") == "1":
        GOLDEN.write_text(json.dumps(actual, ensure_ascii=True, indent=2) + "\n")
    assert actual == json.loads(GOLDEN.read_text())


