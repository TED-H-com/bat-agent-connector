@pytest.mark.parametrize("row", VECTORS.get("profile_indexes", []), ids=lambda row: row["id"])
def test_profile_index_vectors_through_real_listing(tmp_path, row):
    listing = parse_profile_index(row["index"])
    assert asdict(listing) == row["expected"]
    index = tmp_path / "index.json"
    index.write_text(row["index"])
    store = tmp_path / "remote-tokens.enc.json"
    secret = "synthetic-sensitive-value"
    store.write_text(json.dumps({"enc": False, "data": json.dumps({
        "tokens": {p["id"]: secret for p in listing.profiles}})}))
    store.chmod(0o600)
    before = [(p.read_bytes(), p.stat().st_mtime_ns) for p in (index, store)]
    actual, error = setup._profiles({"bat": {"profiles_dir": str(tmp_path)}})
    assert actual == [{"id": p["id"], "name": p["name"], "url": p["endpoint"]["url"],
        "fingerprint": p["fingerprint"], "profile_id": p["remote_profile_id"],
        "token_available": True, "token_state": "available"} for p in listing.profiles]
    expected_error = (None if listing.profiles else
        "BAT profiles are unavailable; enter the host and its trusted fingerprint"
        if listing.reason == "PROFILE_INDEX_INVALID" else "No complete remote BAT profiles were found")
    assert error == expected_error
    assert secret not in repr(listing) + repr(actual) + str(error)
    assert [(p.read_bytes(), p.stat().st_mtime_ns) for p in (index, store)] == before


def test_profile_index_byte_bound():
    assert parse_profile_index(" " * (1024 * 1024 - 2) + "{}").reason == "NO_COMPLETE_PROFILES"
    assert parse_profile_index(" " * (1024 * 1024 - 1) + "{}").reason == "PROFILE_INDEX_INVALID"


@pytest.mark.parametrize("row", VECTORS["token_stores"], ids=lambda row: row["id"])
def test_all_python_readers_match_vectors(tmp_path, row):
    write_profile(tmp_path, "", profile_id=row["profile_id"])
    path = tmp_path / "remote-tokens.enc.json"
    path.write_text(row["store"])
    before = path.read_bytes(), path.stat().st_mtime_ns
    profiles, error = setup._profiles({"bat": {"profiles_dir": str(tmp_path)}})
    assert error is None
    expected = row["expected"]
    assert profiles[0]["token_state"] == expected["admission"]["state"]
    admitted = expected["admission"]["state"] == "available"
    assert profiles[0]["token_available"] is admitted
    host = config.HostConfig("fixture", profiles[0]["url"], profiles[0]["fingerprint"],
        "bat-profile:" + row["profile_id"], bat_profiles_dir=str(tmp_path))
    assert host.token_available() is (expected["python_runtime"]["state"] == "available")
    if expected["python_runtime"]["state"] == "available":
        assert host.resolve_token() == read_token_store(tmp_path, mode=TokenMode.LEGACY_RUNTIME).lookup(row["profile_id"]).token
    else:
        with pytest.raises(config.TokenUnavailable):
            host.resolve_token()
    if admitted:
        assert expected["python_runtime"]["state"] == "available"
        assert expected["rust_legacy_fleet"]["state"] == "available"
    assert (path.read_bytes(), path.stat().st_mtime_ns) == before


@pytest.mark.parametrize("mode", list(TokenMode))
def test_results_never_expose_token_or_parser_exception(mode, caplog):
    secret = "synthetic-sensitive-value"
    contents = json.dumps({"enc": False, "data": json.dumps({"tokens": {"remote-1": secret}})})
    store = parse_token_store(contents, mode=mode)
    result = store.lookup("remote-1")
    assert result.token == secret
    assert secret not in repr(store) + repr(result) + result.reason + caplog.text
    broken = parse_token_store(contents[:-1], mode=mode)
    assert secret not in repr(broken) + broken.reason + caplog.text


