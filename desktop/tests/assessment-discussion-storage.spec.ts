import {test,expect} from '@playwright/test';
import {demoFixture} from './demo/index.ts';
import {assessmentRoundtrip} from './assessment-roundtrip-fixture.ts';
import {mountConversation} from './conversation-fixture.ts';
import {discussHref} from '../src/pm-discuss-link.js';
import {sessionHref} from '../src/session-navigation.js';
import {selectionFromResult,assessmentQuery} from '../src/pm-assessment-selection.js';
for(const native of [false,true])test(`discussion persistence excludes the pin and recovers the ordinary draft ${native?'IPC':'HTTP'}`,async({page})=>{
  const f=demoFixture({discussions:true}),work='wi_'+'1'.repeat(20),r=assessmentRoundtrip(f,f.ids.workspaceId,work);
  const pin=selectionFromResult({partition:'fixture-partition',envelope:r.state.envelope,reference:r.ref});
  const from=sessionHref({host:'fixture-host',sessionId:'fixture-session',workspaceId:f.ids.workspaceId,workItemId:work,attemptId:r.state.attempt.attempt_id});
  const destination=(origin:string)=>'/dashboard/'+discussHref({workspaceId:f.ids.workspaceId,title:'Review original result',from:origin});
  await mountConversation(page,native,f.dispatch);await page.goto(destination(from));
  const composer=page.locator('[data-discussion-composer]');await composer.fill('Keep the existing ordinary draft');
  const keys=await page.evaluate(()=>Object.keys(localStorage).filter(key=>key.includes('pm.thread.create')));
  await page.goto(destination(from+'&'+assessmentQuery(pin,pin.partition)));
  await expect(composer).toHaveValue('Keep the existing ordinary draft');
  await composer.fill('Keep this reviewed note');
  const all=()=>page.evaluate(()=>Object.entries(localStorage));
  expect((await all()).filter(([key,value])=>/qa_[a-z_]+/.test(key+value))).toEqual([]);
  expect((await all()).filter(([key])=>key.includes('pm.thread.create')).map(([key])=>key)).toEqual(keys);
  expect(f.discussion.writes).toEqual([]);
  await page.locator('[data-pm-action="pm.thread.create"] button[type=submit]').click();
  await expect.poll(()=>f.discussion.writes.some((row:any)=>row.body.action==='pm.thread.create')).toBe(true);
  await expect.poll(async()=>(await all()).some(([key])=>key.includes('.discussion-origin.')&&!key.endsWith('index'))).toBe(true);
  expect((await all()).filter(([key,value])=>/qa_[a-z_]+/.test(key+value))).toEqual([]);
  const origins=(await all()).filter(([key])=>key.includes('.discussion-origin.')&&!key.endsWith('index')).map(([,value])=>JSON.parse(value));
  expect(origins.some(value=>value.from===from)).toBe(true);
});
